#!/usr/bin/env python3
"""Patch data-a-live's xnu.yml for the macos-14 retirement (iig replay).

Why: only Apple's `iig` is Xcode-version-bound. Xcode 16+ emits IORPC.kernelContent,
which xnu-8796 does not understand. Xcode 15.x no longer exists on any hosted runner
(macos-14 retired 2026-11-02). Fix: replay the 17 DriverKit iig outputs generated by
Xcode 15.4 (iig DriverKit-286), from the ios-fuxi capture run, committed under
xnu/iig-pregen/ and injected with IIG=/XNU_IIG_CACHE= for the build.

Run from the repo root:  python wsl/patch_xnu_yml_iig.py
Writes .github/workflows/xnu.yml in place (idempotent).
"""
import pathlib
import sys

WF = pathlib.Path(".github/workflows/xnu.yml")
MARK = "# iig replay (macos-14 retirement)"
CACHE_REL = "xnu/iig-pregen"

OLD_INPUTS_TAIL = """      keep_going:
        description: make -k (collect all compile errors in one run)
        default: "true"
"""

NEW_INPUTS_TAIL = OLD_INPUTS_TAIL + f"""      {MARK.split(' (')[0].replace('# ', '').replace(' ', '_')}:
        description: DriverKit iig outputs replayed from {CACHE_REL}
        default: "1"
"""

OLD_ENV_TAIL = """  MACHINE_CONFIG: ${{ inputs.machine_config || 'PANDORA' }}
"""

NEW_ENV_TAIL = OLD_ENV_TAIL + f"""  {MARK}
  # iig is the ONLY Xcode-version-bound tool: DriverKit's iig turns iokit/DriverKit/*.iig
  # into *.h + *.iig.cpp. Xcode 16+ emits IORPC.kernelContent, which xnu-8796 rejects.
  # These 17 pairs were generated by Xcode 15.4 (iig DriverKit-286) and are byte-identical
  # to what a macos-14 Xcode 15 build produced (ios-fuxi capture run 41098982212).
  XNU_IIG_CACHE: ${{{{ github.workspace }}}}/{CACHE_REL}
"""

OLD_PATCH_STEP_ANCHOR = """          ls dxb/patches
"""

NEW_PATCH_STEP_ANCHOR = """          ls dxb/patches

      - name: Verify iig replay cache
        run: |
          python3 xnu-iig-cache.py --verify "$XNU_DIR" "$XNU_IIG_CACHE"
        env:
          XNU_DIR: ${{ github.workspace }}/xnu
          XNU_IIG_CACHE: ${{ github.workspace }}/xnu/iig-pregen
"""

OLD_BUILD_ENV = """        env:
          # keep going after errors so one run reports every compile failure
          MAKEFLAGS: ${{ inputs.keep_going == 'false' && '' || '-k' }}
"""

NEW_BUILD_ENV = """        env:
          # keep going after errors so one run reports every compile failure
          MAKEFLAGS: ${{ inputs.keep_going == 'false' && '' || '-k' }}
          # iig replay: never run Xcode's iig (version-bound); use the Xcode 15.4 outputs.
          IIG: ${{ github.workspace }}/xnu-iig-cache.py
          XNU_IIG_CACHE: ${{ github.workspace }}/xnu/iig-pregen
"""


def main():
    if not WF.is_file():
        sys.exit(f"missing {WF} (run from the repo root)")
    text = WF.read_text()

    if MARK in text:
        print("already patched")
        return

    for old, new, what in (
        (OLD_INPUTS_TAIL, NEW_INPUTS_TAIL, "inputs"),
        (OLD_ENV_TAIL, NEW_ENV_TAIL, "env"),
        (OLD_PATCH_STEP_ANCHOR, NEW_PATCH_STEP_ANCHOR, "verify step"),
        (OLD_BUILD_ENV, NEW_BUILD_ENV, "build env"),
    ):
        if old not in text:
            sys.exit(f"anchor for {what} not found - workflow changed upstream?")
        text = text.replace(old, new, 1)

    # macos-14 is retired: move to macos-15 (Xcode 16.2 default is fine with iig replay)
    text = text.replace("runs-on: macos-14", "runs-on: macos-15")
    # The "Xcode 15.x only" Xcode selection must not pick the newest Xcode blindly for
    # anything version-bound; iig replay makes clang/ld choice harmless, keep as is.

    WF.write_text(text)
    print(f"patched {WF}")
    print("  runs-on -> macos-15")
    print(f"  IIG replay from {CACHE_REL} (commit xnu-iig-cache.py + {CACHE_REL}/)")


if __name__ == "__main__":
    main()
